#!/usr/bin/env bash
# Turn a finished `next build` (output: 'standalone') into the tarball the library server runs.
# Used by .github/workflows/release.yml; can be run locally to inspect the result.
#
#   deploy/package.sh [out-dir]     -> <out-dir>/daaho-portfolio.tar.gz and .sha256
set -euo pipefail
cd "$(dirname "$0")/.."
OUT="${1:-dist}"
APP="$OUT/app"

[ -f .next/standalone/server.js ] || { echo "No standalone build; run pnpm build first." >&2; exit 1; }
rm -rf "$OUT"
mkdir -p "$APP"
cp -R .next/standalone/. "$APP/"
mkdir -p "$APP/.next"
cp -R .next/static "$APP/.next/static"
[ -d public ] && cp -R public "$APP/public"

# Next copies the build machine's .env files into the standalone folder. They must never ship:
# the server reads its own settings from /opt/next_js/daaho/shared/.env.
find "$APP" -path "$APP/node_modules" -prune -o -name '.env*' -print -exec rm -f {} +

# The server starts the app with `npm run start` (systemd unit generated by Puppet).
cat > "$APP/package.json" <<'JSON'
{
  "name": "daaho-portfolio",
  "private": true,
  "type": "module",
  "scripts": {
    "start": "PORT=${PORT:-3031} HOSTNAME=${HOSTNAME_BIND:-127.0.0.1} node server.js"
  }
}
JSON

{
  echo "commit=${GITHUB_SHA:-$(git rev-parse HEAD)}"
  echo "built=$(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "node=$(node -v)"
  echo "platform=$(node -p 'process.platform + "-" + process.arch')"
} > "$APP/BUILD_INFO"

tar -czf "$OUT/daaho-portfolio.tar.gz" -C "$APP" .
(cd "$OUT" && shasum -a 256 daaho-portfolio.tar.gz > daaho-portfolio.tar.gz.sha256)
du -h "$OUT/daaho-portfolio.tar.gz"
